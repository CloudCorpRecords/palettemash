/* PaletteMash — core generative blending library.
   Pure JS, no dependencies. Works in Node (smoke test / PNG export)
   and in the browser (the web UI draws the same buffers to canvas).

   IMPORTANT (art ethics): every source "artwork" in this tool is an
   ORIGINAL procedural rendering generated by this code at runtime,
   inspired by public-domain works. No image file of any artist's work
   is bundled, scraped, downloaded, or transformed. See SOURCES.md. */

// ---------- deterministic RNG ----------
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---------- image buffer helpers ----------
function makeImage(w, h) { return { w, h, data: new Uint8ClampedArray(w * h * 4) }; }
function setPx(img, x, y, r, g, b, a = 255) {
  x |= 0; y |= 0;
  if (x < 0 || y < 0 || x >= img.w || y >= img.h) return;
  const i = (y * img.w + x) * 4;
  img.data[i] = r; img.data[i + 1] = g; img.data[i + 2] = b; img.data[i + 3] = a;
}
function blendPx(img, x, y, r, g, b, alpha) {
  x |= 0; y |= 0;
  if (x < 0 || y < 0 || x >= img.w || y >= img.h) return;
  const i = (y * img.w + x) * 4;
  img.data[i] = img.data[i] * (1 - alpha) + r * alpha;
  img.data[i + 1] = img.data[i + 1] * (1 - alpha) + g * alpha;
  img.data[i + 2] = img.data[i + 2] * (1 - alpha) + b * alpha;
  img.data[i + 3] = 255;
}
function fill(img, r, g, b) {
  for (let i = 0; i < img.data.length; i += 4) {
    img.data[i] = r; img.data[i + 1] = g; img.data[i + 2] = b; img.data[i + 3] = 255;
  }
}
function hex(r, g, b) {
  return '#' + [r, g, b].map(v => Math.round(v).toString(16).padStart(2, '0')).join('');
}
function mix(c1, c2, t) {
  return [c1[0] + (c2[0] - c1[0]) * t, c1[1] + (c2[1] - c1[1]) * t, c1[2] + (c2[2] - c1[2]) * t];
}

