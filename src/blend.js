function paintSwirlNight(w, h, seed) {
  const img = makeImage(w, h); const rnd = mulberry32(seed);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const t = y / h;
    const c = mix([16, 24, 72], [38, 62, 130], 1 - t);
    setPx(img, x, y, c[0], c[1], c[2]);
  }
  // spiral flow strokes
  const cx = w * 0.68, cy = h * 0.34;
  for (let s = 0; s < 2600; s++) {
    const ang = rnd() * Math.PI * 2, rad = 8 + Math.pow(rnd(), 1.6) * w * 0.30;
    let x = cx + Math.cos(ang) * rad, y = cy + Math.sin(ang) * rad * 0.62;
    const steps = 14 + rnd() * 22;
    const col = rnd() < 0.72 ? mix([70, 100, 180], [140, 170, 230], rnd()) : mix([230, 200, 90], [250, 230, 160], rnd());
    for (let k = 0; k < steps; k++) {
      const a2 = Math.atan2((y - cy) / 0.62, x - cx) + 1.35;
      x += Math.cos(a2) * 2.4; y += Math.sin(a2) * 2.4 * 0.62;
      blendPx(img, x, y, col[0], col[1], col[2], 0.35);
      blendPx(img, x + 1, y, col[0], col[1], col[2], 0.2);
    }
  }
  // stars + moon
  for (let s = 0; s < 11; s++) {
    const sx = rnd() * w, sy = rnd() * h * 0.55, sr = 3 + rnd() * 7;
    for (let dy = -sr; dy <= sr; dy++) for (let dx = -sr; dx <= sr; dx++) {
      const d = Math.sqrt(dx * dx + dy * dy);
      if (d < sr) blendPx(img, sx + dx, sy + dy, 246, 224, 130, 0.85 * (1 - d / sr) + 0.1);
    }
  }
  for (let dx = -16; dx <= 16; dx++) for (let dy = -16; dy <= 16; dy++) {
    if (dx * dx + dy * dy < 200) blendPx(img, w * 0.14 + dx, h * 0.16 + dy, 250, 236, 170, 0.95);
    if (dx * dx + dy * dy >= 200 && dx * dx + dy * dy < 290) blendPx(img, w * 0.14 + dx, h * 0.16 + dy, 250, 236, 170, 0.25);
  }
  // dark rolling hill
  for (let x = 0; x < w; x++) {
    const top = h * 0.80 + Math.sin(x / w * 5.1) * h * 0.045;
    for (let y = Math.max(0, top | 0); y < h; y++) setPx(img, x, y, 10, 14, 30);
  }
  return img;
}

function paintGreatWave(w, h, seed) {
  const img = makeImage(w, h); const rnd = mulberry32(seed);
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const t = y / h;
    const c = mix([232, 224, 204], [196, 204, 208], t);
    setPx(img, x, y, c[0], c[1], c[2]);
  }
  // distant mountain triangle
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const mx = w * 0.60, base = h * 0.72, peak = h * 0.44;
    if (y > peak && y < base) {
      const half = (y - peak) / (base - peak) * w * 0.16;
      if (Math.abs(x - mx) < half) setPx(img, x, y, 96, 110, 128);
      if (y < peak + (base - peak) * 0.22 && Math.abs(x - mx) < half * 0.35) setPx(img, x, y, 240, 240, 238);
    }
  }
  // layered wave arcs
  const waves = [
    { cx: w * 0.30, cy: h * 1.06, r0: h * 0.62, col: [24, 52, 104] },
    { cx: w * 0.34, cy: h * 1.02, r0: h * 0.52, col: [36, 78, 138] },
    { cx: w * 0.38, cy: h * 0.98, r0: h * 0.42, col: [58, 110, 168] },
    { cx: w * 0.42, cy: h * 0.95, r0: h * 0.33, col: [240, 244, 246] },
  ];
  for (const wv of waves) {
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
      const d = Math.sqrt((x - wv.cx) ** 2 + (y - wv.cy) ** 2);
      const lip = Math.sin(Math.atan2(y - wv.cy, x - wv.cx) * 7 + wv.r0) * 5;
      if (d < wv.r0 + lip && y < wv.cy) setPx(img, x, y, wv.col[0], wv.col[1], wv.col[2]);
    }
  }
  // foam claws + spray
  for (let s = 0; s < 900; s++) {
    const ang = -Math.PI * (0.15 + rnd() * 0.7), rad = h * (0.30 + rnd() * 0.10);
    const x = w * 0.42 + Math.cos(ang) * rad * 1.15, y = h * 0.95 + Math.sin(ang) * rad;
    blendPx(img, x, y, 250, 252, 252, 0.8); blendPx(img, x + 1, y + 1, 250, 252, 252, 0.5);
  }
  for (let s = 0; s < 260; s++) {
    const x = w * (0.08 + rnd() * 0.5), y = h * (0.18 + rnd() * 0.35);
    blendPx(img, x, y, 250, 252, 252, 0.55);
  }
  return img;
}

function paintGridComposition(w, h, seed) {
  const img = makeImage(w, h); const rnd = mulberry32(seed);
  fill(img, 238, 234, 222);
  const xs = [0, 0.14, 0.46, 0.60, 0.86, 1].map(t => Math.round(t * w));
  const ys = [0, 0.22, 0.58, 0.74, 1].map(t => Math.round(t * h));
  const fills = { '1,0': [196, 40, 34], '3,1': [38, 74, 150], '0,2': [232, 186, 44], '2,2': [196, 40, 34], '4,1': [232, 186, 44], '1,3': [38, 74, 150] };
  for (let gy = 0; gy < ys.length - 1; gy++) for (let gx = 0; gx < xs.length - 1; gx++) {
    const c = fills[gx + ',' + gy];
    if (!c) continue;
    for (let y = ys[gy]; y < ys[gy + 1]; y++) for (let x = xs[gx]; x < xs[gx + 1]; x++) setPx(img, x, y, c[0], c[1], c[2]);
  }
  const lw = Math.max(4, Math.round(w * 0.012));
  for (const x of xs) for (let y = 0; y < h; y++) for (let k = 0; k < lw; k++) setPx(img, x + k - (lw >> 1), y, 18, 18, 18);
  for (const y of ys) for (let x = 0; x < w; x++) for (let k = 0; k < lw; k++) setPx(img, x, y + k - (lw >> 1), 18, 18, 18);
  void rnd;
  return img;
}

