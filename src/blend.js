// ---------- palette extraction ----------
function extractPalette(img, count = 6) {
  const buckets = new Map();
  const step = Math.max(1, Math.floor(Math.sqrt((img.w * img.h) / 9000)));
  for (let y = 0; y < img.h; y += step) for (let x = 0; x < img.w; x += step) {
    const i = (y * img.w + x) * 4;
    const r = img.data[i], g = img.data[i + 1], b = img.data[i + 2];
    const key = ((r >> 5) << 6) | ((g >> 5) << 3) | (b >> 5);
    let bk = buckets.get(key);
    if (!bk) { bk = { n: 0, r: 0, g: 0, b: 0 }; buckets.set(key, bk); }
    bk.n++; bk.r += r; bk.g += g; bk.b += b;
  }
  const sorted = [...buckets.values()].sort((a, b) => b.n - a.n);
  const total = sorted.reduce((s, b) => s + b.n, 0);
  const picked = [];
  for (const bk of sorted) {
    const c = [bk.r / bk.n, bk.g / bk.n, bk.b / bk.n];
    if (picked.every(p => Math.hypot(p.rgb[0] - c[0], p.rgb[1] - c[1], p.rgb[2] - c[2]) > 42)) {
      picked.push({ rgb: c, hex: hex(c[0], c[1], c[2]), share: bk.n / total });
    }
    if (picked.length >= count) break;
  }
  return picked;
}

// palette from arbitrary RGBA pixel data (e.g. a user-supplied local
// image drawn to a browser canvas) — same algorithm, no upload anywhere.
function paletteFromPixels(data, w, h, count = 6) {
  return extractPalette({ w, h, data }, count);
}

// ---------- the mashup renderer ----------
function renderMashup(sourceImgs, opts = {}) {
  const w = opts.width || 960, h = opts.height || 720;
  const seed = opts.seed || 42;
  const turbulence = opts.turbulence != null ? opts.turbulence : 0.6;
  const rnd = mulberry32(seed);
  const img = makeImage(w, h);
  const pals = sourceImgs.map(s => extractPalette(s.img, 6));
  const palA = pals[0];                                   // movement
  const palB = pals[1] || pals[0];                        // atmosphere
  const palC = sourceImgs.length > 2 ? pals[2] : null;    // structure

  // 1) atmosphere: diagonal gradient wash between atmosphere palettes
  const top = palB[0].rgb, mid = (palB[2] || palB[0]).rgb, bot = (palA[0] || palB[0]).rgb;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const t = (x / w) * 0.35 + (y / h) * 0.65;
    const c = t < 0.5 ? mix(top, mid, t * 2) : mix(mid, bot, (t - 0.5) * 2);
    setPx(img, x, y, c[0], c[1], c[2]);
  }
  // soft radial light pools
  for (let p = 0; p < 5; p++) {
    const px = rnd() * w, py = rnd() * h, pr = (0.18 + rnd() * 0.25) * w;
    const col = palB[Math.floor(rnd() * Math.min(4, palB.length))].rgb;
    for (let y = Math.max(0, py - pr); y < Math.min(h, py + pr); y++) for (let x = Math.max(0, px - pr); x < Math.min(w, px + pr); x++) {
      const d = Math.hypot(x - px, y - py) / pr;
      if (d < 1) blendPx(img, x, y, col[0], col[1], col[2], 0.16 * (1 - d));
    }
  }
  // 2) structure (optional 3rd source): translucent geometric shards
  if (palC) {
    const nx = 5, ny = 4;
    for (let gy = 0; gy < ny; gy++) for (let gx = 0; gx < nx; gx++) {
      if (rnd() < 0.45) continue;
      const col = palC[Math.floor(rnd() * palC.length)].rgb;
      const x0 = (gx / nx) * w + rnd() * 20, y0 = (gy / ny) * h + rnd() * 20;
      const x1 = ((gx + 1) / nx) * w - rnd() * 20, y1 = ((gy + 1) / ny) * h - rnd() * 20;
      for (let y = y0; y < y1; y++) for (let x = x0; x < x1; x++) blendPx(img, x, y, col[0], col[1], col[2], 0.34);
      for (let x = x0; x < x1; x++) { blendPx(img, x, y0, 16, 16, 16, 0.5); blendPx(img, x, y1, 16, 16, 16, 0.5); }
      for (let y = y0; y < y1; y++) { blendPx(img, x0, y, 16, 16, 16, 0.5); blendPx(img, x1, y, 16, 16, 16, 0.5); }
    }
  }
  // 3) movement: flow-field ribbons in the movement palette
  const ribbons = 130 + Math.floor(turbulence * 120);
  for (let rI = 0; rI < ribbons; rI++) {
    let x = rnd() * w, y = rnd() * h;
    const col = palA[Math.floor(rnd() * palA.length)].rgb;
    const steps = 60 + rnd() * 160, thick = rnd() < 0.35 ? 2 : 1;
    for (let k = 0; k < steps; k++) {
      const a = Math.sin(x / (90 + turbulence * 160)) * 1.9 + Math.cos(y / (70 + turbulence * 120)) * 1.4 + rnd() * 0.25;
      x += Math.cos(a) * 2.6; y += Math.sin(a) * 2.6;
      if (x < -10 || y < -10 || x > w + 10 || y > h + 10) break;
      const fade = 0.52 * (1 - k / steps) + 0.10;
      blendPx(img, x, y, col[0], col[1], col[2], fade);
      if (thick) blendPx(img, x + 1, y + 1, col[0], col[1], col[2], fade * 0.7);
    }
  }
  // accent orbs from the movement palette's lightest colour
  const light = palA.reduce((best, p) => {
    const lum = p.rgb[0] + p.rgb[1] + p.rgb[2];
    return lum > best.lum ? { lum, rgb: p.rgb } : best;
  }, { lum: -1, rgb: [255, 240, 180] }).rgb;
  for (let s = 0; s < 14; s++) {
    const sx = rnd() * w, sy = rnd() * h, sr = 2 + rnd() * 6;
    for (let dy = -sr; dy <= sr; dy++) for (let dx = -sr; dx <= sr; dx++) {
      const d = Math.hypot(dx, dy);
      if (d < sr) blendPx(img, sx + dx, sy + dy, light[0], light[1], light[2], 0.5 * (1 - d / sr));
    }
  }
  // 4) grain + vignette
  for (let i = 0; i < img.data.length; i += 4) {
    const n = (rnd() - 0.5) * 14;
    img.data[i] += n; img.data[i + 1] += n; img.data[i + 2] += n;
  }
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const d = Math.hypot((x - w / 2) / (w / 2), (y - h / 2) / (h / 2));
    if (d > 0.85) {
      const i = (y * img.w + x) * 4, f = 1 - Math.min(0.35, (d - 0.85) * 0.5);
      img.data[i] *= f; img.data[i + 1] *= f; img.data[i + 2] *= f;
    }
  }
  return { img, palettes: pals };
}

// ---------- curation statement ----------
function curationStatement(sourceMetas, palettes, opts = {}) {
  const names = sourceMetas.map(s => s.title);
  const roles = ['movement (flow-field ribbons)', 'atmosphere (gradient wash + light pools)'];
  if (sourceMetas.length > 2) roles.push('structure (geometric shards)');
  const lines = [];
  lines.push('CURATION STATEMENT — how this piece was made, and from what');
  lines.push('');
  lines.push(`This generative piece remixes ${names.length} procedural studies, each an original rendering by this tool's own code, inspired by public-domain works:`);
  sourceMetas.forEach((s, i) => {
    const top3 = palettes[i].slice(0, 3).map(p => p.hex).join(', ');
    lines.push(`• ${s.title} — ${roles[i]}. Palette drawn from it: ${top3}. Source note: ${s.inspiration}.`);
  });
  lines.push('');
  lines.push('Method: palettes were extracted from the source pixels by colour quantisation, then recomposed — the atmosphere is a gradient wash of one palette, the movement is a seeded flow field painted in another, and (with three sources) geometric shards carry the third. No pixels from any source artwork appear in the output; only their colours do. No copyrighted or scraped artwork was used at any step — every visual in this project was generated by the code in this repository.');
  lines.push(`Seed: ${opts.seed || 42} · Turbulence: ${opts.turbulence != null ? opts.turbulence : 0.6} · Generated locally by PaletteMash; nothing was uploaded anywhere.`);
  return lines.join('\n');
}

// ---------- PNG encoding (Node, built-in zlib only) ----------
const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xEDB88320 ^ (c >>> 1)) : (c >>> 1);
    t[n] = c;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xFFFFFFFF;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xFF] ^ (c >>> 8);
  return (c ^ 0xFFFFFFFF) >>> 0;
}
function pngChunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length, 0);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}
function encodePNG(img) {
  const zlib = require('zlib');
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(img.w, 0); ihdr.writeUInt32BE(img.h, 4);
  ihdr[8] = 8; ihdr[9] = 6; // 8-bit RGBA
  const raw = Buffer.alloc((img.w * 4 + 1) * img.h);
  for (let y = 0; y < img.h; y++) {
    raw[y * (img.w * 4 + 1)] = 0;
    Buffer.from(img.data.buffer, y * img.w * 4, img.w * 4).copy(raw, y * (img.w * 4 + 1) + 1);
  }
  const idat = zlib.deflateSync(raw, { level: 6 });
  return Buffer.concat([sig, pngChunk('IHDR', ihdr), pngChunk('IDAT', idat), pngChunk('IEND', Buffer.alloc(0))]);
}

